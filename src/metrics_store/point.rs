// Both representations consume borrowed JSON strings before the line buffer is reused.
fn deserialize_text<'de, D, T>(deserializer: D) -> Result<T, D::Error>
where
    D: Deserializer<'de>,
    T: for<'a> From<&'a str>,
{
    struct Text<T>(PhantomData<T>);
    impl<'de, T: for<'a> From<&'a str>> Visitor<'de> for Text<T> {
        type Value = T;

        fn expecting(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
            f.write_str("a telemetry string")
        }

        fn visit_str<E: serde::de::Error>(self, text: &str) -> Result<T, E> {
            Ok(text.into())
        }
    }
    deserializer.deserialize_str(Text(PhantomData))
}

static STANDARD_CODES: &[&str] = &[
    "check",
    DisconnectReason::Online.as_str(),
    "login_ok",
    "login_fail",
    "OFFLINE",
    DisconnectReason::LinkDown.as_str(),
    DisconnectReason::NoIp.as_str(),
    DisconnectReason::NoGateway.as_str(),
    DisconnectReason::GatewayUnreachable.as_str(),
    DisconnectReason::DnsFailure.as_str(),
    DisconnectReason::AuthExpired.as_str(),
    DisconnectReason::InternetTimeout.as_str(),
    DisconnectReason::UplinkUnreachable.as_str(),
    DisconnectReason::LoginRejected.as_str(),
    DisconnectReason::PortalUnavailable.as_str(),
    DisconnectReason::CredentialsMissing.as_str(),
];

#[derive(Debug, Clone, PartialEq, Eq, Hash)]
pub enum TelemetryCode {
    Standard(&'static &'static str),
    Other(Box<str>),
}

impl From<&str> for TelemetryCode {
    fn from(text: &str) -> Self {
        Self::standard(text).unwrap_or_else(|| Self::Other(text.into()))
    }
}

impl From<String> for TelemetryCode {
    fn from(text: String) -> Self {
        Self::standard(&text).unwrap_or_else(|| Self::Other(text.into_boxed_str()))
    }
}

impl TelemetryCode {
    fn standard(text: &str) -> Option<Self> {
        STANDARD_CODES
            .iter()
            .find(|&&code| code == text)
            .map(Self::Standard)
    }

    pub fn as_str(&self) -> &str {
        match self {
            Self::Standard(code) => code,
            Self::Other(text) => text,
        }
    }
}

impl Deref for TelemetryCode {
    type Target = str;
    fn deref(&self) -> &str {
        self.as_str()
    }
}

impl AsRef<str> for TelemetryCode {
    fn as_ref(&self) -> &str {
        self.as_str()
    }
}

impl PartialEq<&str> for TelemetryCode {
    fn eq(&self, other: &&str) -> bool {
        self.as_str() == *other
    }
}

impl Serialize for TelemetryCode {
    fn serialize<S: Serializer>(&self, serializer: S) -> Result<S::Ok, S::Error> {
        serializer.serialize_str(self.as_str())
    }
}

impl<'de> Deserialize<'de> for TelemetryCode {
    fn deserialize<D: Deserializer<'de>>(deserializer: D) -> Result<Self, D::Error> {
        deserialize_text(deserializer)
    }
}

const INLINE_ID_BYTES: usize = 22;

#[derive(Debug, Clone, PartialEq, Eq, Hash)]
pub struct SampleId(IdRepr);

#[derive(Debug, Clone, PartialEq, Eq, Hash)]
enum IdRepr {
    Generated {
        pid: u32,
        epoch: i64,
        seq: u64,
    },
    Inline {
        len: u8,
        bytes: [u8; INLINE_ID_BYTES],
    },
    Other(Box<str>),
}

impl SampleId {
    pub fn generated(pid: u32, epoch: i64, seq: u64) -> Self {
        Self(IdRepr::Generated { pid, epoch, seq })
    }

    fn parse_generated(text: &str) -> Option<Self> {
        // Only canonical decimals can be regenerated byte-for-byte ("01" and "-0" are IDs too).
        fn decimal<T: FromStr>(s: &str) -> Option<T> {
            let digits = s.strip_prefix('-').unwrap_or(s);
            if !digits.as_bytes().first()?.is_ascii_digit() || (digits.starts_with('0') && s != "0")
            {
                return None;
            }
            s.parse().ok()
        }
        let (pid, tail) = text.split_once('-')?;
        let (epoch, seq) = tail.rsplit_once('-')?;
        Some(Self::generated(
            decimal(pid)?,
            decimal(epoch)?,
            decimal(seq)?,
        ))
    }
}

impl From<&str> for SampleId {
    fn from(text: &str) -> Self {
        if let Some(id) = Self::parse_generated(text) {
            return id;
        }
        if text.len() <= INLINE_ID_BYTES {
            let mut bytes = [0; INLINE_ID_BYTES];
            bytes[..text.len()].copy_from_slice(text.as_bytes());
            Self(IdRepr::Inline {
                len: text.len() as u8,
                bytes,
            })
        } else {
            Self(IdRepr::Other(text.into()))
        }
    }
}

impl fmt::Display for SampleId {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        match &self.0 {
            IdRepr::Generated { pid, epoch, seq } => write!(f, "{pid}-{epoch}-{seq}"),
            IdRepr::Inline { len, bytes } => f.write_str(
                std::str::from_utf8(&bytes[..usize::from(*len)]).expect("inline UTF-8 ID"),
            ),
            IdRepr::Other(text) => f.write_str(text),
        }
    }
}

impl Serialize for SampleId {
    fn serialize<S: Serializer>(&self, serializer: S) -> Result<S::Ok, S::Error> {
        serializer.collect_str(self)
    }
}

impl<'de> Deserialize<'de> for SampleId {
    fn deserialize<D: Deserializer<'de>>(deserializer: D) -> Result<Self, D::Error> {
        deserialize_text(deserializer)
    }
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::metrics_store::TelemetryPoint;
    use std::alloc::{GlobalAlloc, Layout, System};
    use std::cell::Cell;
    use std::hint::black_box;

    // Count only the test thread's allocations inside the measured interval.
    thread_local! {
        #[allow(clippy::missing_const_for_thread_local, reason = "Windows GNU also lints the macro's internal initializer")]
        static ALLOCATIONS: Cell<Option<usize>> = const { Cell::new(None) };
    }
    struct CountingAllocator;
    #[global_allocator]
    static ALLOCATOR: CountingAllocator = CountingAllocator;

    fn count_allocation() {
        let _ = ALLOCATIONS.try_with(|counter| {
            if let Some(n) = counter.get() {
                counter.set(Some(n + 1));
            }
        });
    }

    // All pointers, sizes and alignments are forwarded unmodified to the system allocator.
    unsafe impl GlobalAlloc for CountingAllocator {
        unsafe fn alloc(&self, layout: Layout) -> *mut u8 {
            count_allocation();
            unsafe { System.alloc(layout) }
        }
        unsafe fn realloc(&self, ptr: *mut u8, layout: Layout, size: usize) -> *mut u8 {
            count_allocation();
            unsafe { System.realloc(ptr, layout, size) }
        }
        unsafe fn dealloc(&self, ptr: *mut u8, layout: Layout) {
            unsafe { System.dealloc(ptr, layout) }
        }
    }

    fn allocations(f: impl FnOnce()) -> usize {
        ALLOCATIONS.set(Some(0));
        f();
        ALLOCATIONS.replace(None).unwrap()
    }

    #[test]
    fn common_points_decode_generate_clone_and_write_without_allocating() {
        #[cfg(target_pointer_width = "64")]
        assert!(size_of::<TelemetryPoint>() <= 80);
        let row = r#"{"sample_id":"12345-1760000000000000000-42","ts":1,"ms":13,"online":true,"confirmed_offline":false,"reason":"ONLINE","event":"check"}"#;
        assert_eq!(
            allocations(|| {
                for _ in 0..5000 {
                    black_box(serde_json::from_str::<TelemetryPoint>(black_box(row)).unwrap());
                }
            }),
            0
        );
        assert_eq!(
            allocations(|| {
                for &code in STANDARD_CODES {
                    let mut p = TelemetryPoint::check(1, 13, true, black_box(code));
                    p.sample_id = Some(SampleId::generated(u32::MAX, i64::MIN, u64::MAX));
                    let copy = black_box(p.clone());
                    let mut buf = [0u8; 256];
                    serde_json::to_writer(&mut buf[..], &copy).unwrap();
                    black_box(buf);
                    black_box(TelemetryPoint::auth_event(1, true, code));
                    black_box(TelemetryPoint::auth_event(1, false, code));
                    black_box(SampleId::from("short-示例"));
                }
            }),
            0
        );
        let custom = r#"{"sample_id":"a custom ID much longer than 22 bytes","ts":2,"ms":0,"online":false,"reason":"自定义原因","event":"legacy event"}"#;
        assert_eq!(
            allocations(|| {
                black_box(serde_json::from_str::<TelemetryPoint>(black_box(custom)).unwrap());
            }),
            3
        );
    }

    #[test]
    fn json_preserves_legacy_defaults_and_arbitrary_code_and_id_spelling() {
        use serde_json::{json, to_value};
        let old = r#"{"ts":1,"ms":0,"online":false,"reason":"OFFLINE"}"#;
        let p: TelemetryPoint = serde_json::from_str(old).unwrap();
        assert_eq!(p.sample_id, None);
        assert_eq!(p.confirmed_offline, None);
        assert_eq!(
            to_value(p).unwrap(),
            json!({"ts":1,"ms":0,"online":false,"reason":"OFFLINE","event":"check"})
        );
        for id in [
            "",
            "short-1",
            "001-2-3",
            "1--0-1",
            "1-+2-1",
            "1-2-03",
            "1--2-3",
            "4294967295--9223372036854775808-18446744073709551615",
            "exactly-22-byte-string",
            "自定义/带空格 和很长的后缀\\\"\n",
        ] {
            for (reason, event) in [
                ("ONLINE", "check"),
                ("LOGIN_REJECTED", "login_fail"),
                ("OFFLINE", "login_ok"),
                ("自定义\0原因", "AUTH/旧事件"),
            ] {
                let wire = json!({"sample_id":id,"ts":-1,"ms":73,"online":true,"confirmed_offline":false,"reason":reason,"event":event});
                let p: TelemetryPoint = serde_json::from_value(wire.clone()).unwrap();
                assert_eq!(p.reason, reason);
                assert_eq!(p.event, event);
                assert_eq!(to_value(p.clone()).unwrap(), wire);
                assert_eq!(
                    serde_json::from_reader::<_, TelemetryPoint>(
                        serde_json::to_vec(&p).unwrap().as_slice()
                    )
                    .unwrap(),
                    p
                );
            }
        }
    }
}
